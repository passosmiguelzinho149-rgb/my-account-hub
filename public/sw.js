// Kill switch for the retired offline service worker.
// Browsers that still have the old worker fetch this file on their next visit,
// install it, and it then deletes every cached file and unregisters itself,
// so the app always loads fresh code from the network.
self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.map((key) => caches.delete(key)));
      await self.registration.unregister();
      const clients = await self.clients.matchAll({ type: "window" });
      clients.forEach((client) => client.navigate(client.url));
    })(),
  );
});
